		mapping.ref_id,
		mapping.ref_descr,
		count(*) OVER (PARTITION BY mapping.ref_id) AS product_match_count,
		count(*) OVER (PARTITION BY product.id) AS reference_match_count
	FROM mapping
	JOIN public.products AS product
		ON lower(btrim(product.name)) = lower(btrim(mapping.product_name))
		AND product.is_group = false
), updated AS (
	UPDATE public.products AS product
	SET ref_1c = jsonb_build_object(
		'id', candidate.ref_id,
		'descr', candidate.ref_descr
	)
	FROM candidates AS candidate
	WHERE product.id = candidate.product_id
		AND candidate.product_match_count = 1
		AND candidate.reference_match_count = 1
