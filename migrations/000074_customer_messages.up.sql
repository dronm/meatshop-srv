BEGIN;

CREATE TABLE public.customer_messages (
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	max_in_message_id bigint UNIQUE REFERENCES public.max_in_messages(id) ON DELETE SET NULL,
	max_message_id text NOT NULL UNIQUE CHECK (btrim(max_message_id) <> ''),
	max_user_id bigint NOT NULL CHECK (max_user_id > 0),
	max_chat_id bigint,
	customer_id integer REFERENCES public.customers(id) ON DELETE SET NULL,
	sender_name text NOT NULL,
	text text NOT NULL CHECK (text ~ '[^[:space:]]'),
	sent_at timestamptz NOT NULL,
	created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.customer_messages IS
	'Incoming MAX customer text messages. Customer and sender name are snapshots; unassigned messages can be linked later.';

CREATE INDEX customer_messages_customer_created_idx
	ON public.customer_messages (customer_id, created_at DESC, id DESC);
CREATE INDEX customer_messages_created_idx
	ON public.customer_messages (created_at DESC, id DESC);
CREATE INDEX customer_messages_sender_created_idx
	ON public.customer_messages (max_user_id, created_at DESC, id DESC);

CREATE TABLE public.customer_message_reads (
	message_id bigint NOT NULL REFERENCES public.customer_messages(id) ON DELETE CASCADE,
	user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
	read_at timestamptz NOT NULL DEFAULT now(),
	PRIMARY KEY (message_id, user_id)
);
CREATE INDEX customer_message_reads_user_message_idx
	ON public.customer_message_reads (user_id, message_id);

CREATE VIEW public.customer_messages_list AS
SELECT
	m.id, m.max_message_id, m.max_user_id, m.max_chat_id, m.customer_id,
	CASE WHEN c.id IS NULL THEN NULL ELSE
		jsonb_build_object('keys', jsonb_build_object('id', c.id), 'descr', c.name)
	END AS customer,
	m.sender_name, m.text, m.sent_at, m.created_at
FROM public.customer_messages AS m
LEFT JOIN public.customers AS c ON c.id = m.customer_id;

-- Extraction is shared by live ingestion and historical backfill. It runs in
-- the raw update's transaction, including when an older cmd/max is still running.
CREATE FUNCTION public.store_max_customer_message(
	p_id bigint, p_update_type text, p_max_user_id bigint,
	p_max_chat_id bigint, p_message jsonb, p_created_at timestamptz
)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
	v_mid text;
	v_text text;
	v_customer_id integer;
	v_sender_name text;
	v_timestamp text;
	v_sent_at timestamptz := p_created_at;
BEGIN
	IF p_update_type <> 'message_created'
		OR p_max_user_id IS NULL OR p_max_user_id <= 0
		OR p_message #>> '{message,sender,is_bot}' = 'true'
		OR coalesce(p_message #>> '{message,recipient,chat_type}', 'dialog') <> 'dialog'
		OR jsonb_typeof(p_message #> '{message,body,mid}') IS DISTINCT FROM 'string'
		OR jsonb_typeof(p_message #> '{message,body,text}') IS DISTINCT FROM 'string'
	THEN
		RETURN;
	END IF;
	v_mid := btrim(p_message #>> '{message,body,mid}');
	v_text := p_message #>> '{message,body,text}';
	IF v_mid = '' OR v_text !~ '[^[:space:]]' THEN
		RETURN;
	END IF;

	-- Use the same lock as MAX user binding. A concurrent registration must
	-- either be visible here or attach this message after it commits.
	PERFORM pg_advisory_xact_lock(740074, hashint8(p_max_user_id));
	SELECT customer_id, nullif(btrim(app_username), '')
	INTO v_customer_id, v_sender_name
	FROM public.max_users WHERE max_user_id = p_max_user_id;
	v_sender_name := coalesce(v_sender_name,
		nullif(btrim(concat_ws(' ', p_message #>> '{message,sender,first_name}',
			p_message #>> '{message,sender,last_name}')), ''),
		nullif(btrim(p_message #>> '{message,sender,username}'), ''),
		p_max_user_id::text);
	v_timestamp := p_message #>> '{message,timestamp}';
	IF jsonb_typeof(p_message #> '{message,timestamp}') = 'number'
		AND v_timestamp ~ '^[0-9]{1,15}$'
	THEN
		IF v_timestamp::numeric <= 253402300799999 THEN
			v_sent_at := to_timestamp(v_timestamp::double precision / 1000);
		END IF;
	END IF;

	INSERT INTO public.customer_messages (
		max_in_message_id, max_message_id, max_user_id, max_chat_id,
		customer_id, sender_name, text, sent_at, created_at
	)
	VALUES (p_id, v_mid, p_max_user_id, p_max_chat_id,
		v_customer_id, v_sender_name, v_text, v_sent_at, p_created_at)
	ON CONFLICT (max_message_id) DO NOTHING;
END;
$$;

CREATE FUNCTION public.max_in_messages_store_customer_message()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	PERFORM public.store_max_customer_message(NEW.id, NEW.update_type,
		NEW.max_user_id, NEW.max_chat_id, NEW.message, NEW.created_at);
	RETURN NEW;
END;
$$;

CREATE TRIGGER max_in_messages_store_customer_message
AFTER INSERT ON public.max_in_messages
FOR EACH ROW EXECUTE FUNCTION public.max_in_messages_store_customer_message();

CREATE FUNCTION public.max_users_lock_customer_messages()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	PERFORM pg_advisory_xact_lock(740074, hashint8(NEW.max_user_id));
	RETURN NEW;
END;
$$;

CREATE TRIGGER max_users_lock_customer_messages
BEFORE INSERT OR UPDATE OF customer_id, max_user_id ON public.max_users
FOR EACH ROW EXECUTE FUNCTION public.max_users_lock_customer_messages();

CREATE FUNCTION public.max_users_attach_customer_messages()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	IF NEW.customer_id IS NOT NULL THEN
		UPDATE public.customer_messages SET customer_id = NEW.customer_id
		WHERE max_user_id = NEW.max_user_id AND customer_id IS NULL;
		IF FOUND THEN
			PERFORM pg_notify('CustomerMessage.Update',
				jsonb_build_object('max_user_id', NEW.max_user_id, 'customer_id', NEW.customer_id)::text);
		END IF;
	END IF;
	RETURN NEW;
END;
$$;

CREATE TRIGGER max_users_attach_customer_messages
AFTER INSERT OR UPDATE OF customer_id, max_user_id ON public.max_users
FOR EACH ROW EXECUTE FUNCTION public.max_users_attach_customer_messages();

-- Historical messages become unread for every admin. No per-message live
-- notifications are emitted during the import; the client fetches a summary.
SELECT public.store_max_customer_message(id, update_type, max_user_id,
	max_chat_id, message, created_at)
FROM public.max_in_messages
WHERE update_type = 'message_created'
ORDER BY created_at, id;

CREATE FUNCTION public.customer_messages_notify_insert()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
	-- Keep the NOTIFY payload small; fetch authorized text through the API.
	PERFORM pg_notify('CustomerMessage.Create',
		jsonb_build_object('id', NEW.id, 'customer_id', NEW.customer_id,
			'max_user_id', NEW.max_user_id)::text);
	RETURN NEW;
END;
$$;

CREATE TRIGGER customer_messages_notify_insert
AFTER INSERT ON public.customer_messages
FOR EACH ROW EXECUTE FUNCTION public.customer_messages_notify_insert();

