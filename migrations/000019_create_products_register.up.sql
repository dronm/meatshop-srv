	'Order'::text AS recorder_type,
	orders.id::bigint AS recorder_id,
	orders.for_date AS document_date,
	orders.number_1c AS document_number
FROM public.orders AS orders;

COMMENT ON VIEW public.product_register_recorders IS 'Normalizes document headers used as ra_products recorders.';

