CREATE OR REPLACE FUNCTION public.ra_products_remove_acts(
	in_recorder_type text,
	in_recorder_id bigint
)
RETURNS bigint
LANGUAGE sql
AS $function$
	WITH deleted AS (
		DELETE FROM public.ra_products
		WHERE recorder_type = in_recorder_type
			AND recorder_id = in_recorder_id
		RETURNING 1
	)
	SELECT count(*)::bigint
	FROM deleted;
$function$;

COMMENT ON FUNCTION public.ra_products_remove_acts(text, bigint) IS 'Removes all products register actions written by one source recorder and returns the number of removed actions.';

CREATE OR REPLACE FUNCTION public.rg_products_rebuild()
RETURNS void
LANGUAGE plpgsql
AS $function$
BEGIN
	TRUNCATE TABLE public.rg_products, public.rg_products_current;

	INSERT INTO public.rg_products (
		period_start,
		customer_id,
		customer_sale_place_id,
		product_id,
		measure_unit_id,
		quant_required,
		quant
	)
	SELECT
		public.register_month_start(action.effective_at),
		action.customer_id,
		action.customer_sale_place_id,
		action.product_id,
		action.measure_unit_id,
		SUM(action.quant_required)::numeric(19, 4),
		SUM(action.quant)::numeric(19, 4)
	FROM public.ra_products AS action
	GROUP BY
		public.register_month_start(action.effective_at),
		action.customer_id,
		action.customer_sale_place_id,
		action.product_id,
		action.measure_unit_id
	HAVING SUM(action.quant_required) <> 0 OR SUM(action.quant) <> 0;

	INSERT INTO public.rg_products_current (
		customer_id,
		customer_sale_place_id,
		product_id,
		measure_unit_id,
		quant_required,
		quant
	)
	SELECT
		action.customer_id,
		action.customer_sale_place_id,
		action.product_id,
		action.measure_unit_id,
		SUM(action.quant_required)::numeric(19, 4),
		SUM(action.quant)::numeric(19, 4)
	FROM public.ra_products AS action
	GROUP BY
		action.customer_id,
		action.customer_sale_place_id,
		action.product_id,
		action.measure_unit_id
	HAVING SUM(action.quant_required) <> 0 OR SUM(action.quant) <> 0;
END;
$function$;

COMMENT ON FUNCTION public.rg_products_rebuild() IS 'Rebuilds all products register aggregates from the authoritative ra_products ledger.';

CREATE OR REPLACE FUNCTION public.rg_products_balance(
	in_customer_ids integer[] DEFAULT NULL,
	in_customer_sale_place_ids integer[] DEFAULT NULL,
	in_product_ids integer[] DEFAULT NULL,
	in_measure_unit_ids integer[] DEFAULT NULL
)
RETURNS TABLE (
	customer_id integer,
	customer_sale_place_id integer,
	product_id integer,
	measure_unit_id integer,
	quant_required numeric(19, 4),
	quant numeric(19, 4)
)
LANGUAGE sql
STABLE
AS $function$
	SELECT
		balance.customer_id,
		balance.customer_sale_place_id,
		balance.product_id,
		balance.measure_unit_id,
		balance.quant_required,
		balance.quant
	FROM public.rg_products_current AS balance
	WHERE (
		in_customer_ids IS NULL
		OR cardinality(in_customer_ids) = 0
		OR balance.customer_id = ANY(in_customer_ids)
	)
	AND (
		in_customer_sale_place_ids IS NULL
		OR cardinality(in_customer_sale_place_ids) = 0
		OR balance.customer_sale_place_id = ANY(in_customer_sale_place_ids)
	)
	AND (
		in_product_ids IS NULL
		OR cardinality(in_product_ids) = 0
		OR balance.product_id = ANY(in_product_ids)
	)
	AND (
		in_measure_unit_ids IS NULL
		OR cardinality(in_measure_unit_ids) = 0
		OR balance.measure_unit_id = ANY(in_measure_unit_ids)
	)
	AND (balance.quant_required <> 0 OR balance.quant <> 0)
	ORDER BY
		balance.customer_id,
		balance.customer_sale_place_id,
		balance.product_id,
		balance.measure_unit_id;
$function$;

COMMENT ON FUNCTION public.rg_products_balance(integer[], integer[], integer[], integer[]) IS 'Returns fast current accumulated totals from the products register.';

CREATE OR REPLACE FUNCTION public.rg_products_balance(
	in_effective_at timestamptz,
	in_customer_ids integer[] DEFAULT NULL,
	in_customer_sale_place_ids integer[] DEFAULT NULL,
	in_product_ids integer[] DEFAULT NULL,
	in_measure_unit_ids integer[] DEFAULT NULL
)
RETURNS TABLE (
	customer_id integer,
	customer_sale_place_id integer,
	product_id integer,
	measure_unit_id integer,
	quant_required numeric(19, 4),
	quant numeric(19, 4)
)
LANGUAGE sql
STABLE
AS $function$
	WITH boundary AS (
		SELECT
			public.register_month_start(in_effective_at) AS period_start,
			public.register_month_start_at(in_effective_at) AS period_start_at
	), movements AS (
		SELECT
			period.customer_id,
			period.customer_sale_place_id,
			period.product_id,
			period.measure_unit_id,
			period.quant_required,
			period.quant
		FROM public.rg_products AS period
		CROSS JOIN boundary
		WHERE period.period_start < boundary.period_start
			AND (
				in_customer_ids IS NULL
				OR cardinality(in_customer_ids) = 0
				OR period.customer_id = ANY(in_customer_ids)
			)
			AND (
				in_customer_sale_place_ids IS NULL
				OR cardinality(in_customer_sale_place_ids) = 0
				OR period.customer_sale_place_id = ANY(in_customer_sale_place_ids)
			)
			AND (
				in_product_ids IS NULL
				OR cardinality(in_product_ids) = 0
				OR period.product_id = ANY(in_product_ids)
			)
			AND (
				in_measure_unit_ids IS NULL
				OR cardinality(in_measure_unit_ids) = 0
				OR period.measure_unit_id = ANY(in_measure_unit_ids)
			)

		UNION ALL

		SELECT
			action.customer_id,
			action.customer_sale_place_id,
			action.product_id,
			action.measure_unit_id,
			action.quant_required,
			action.quant
		FROM public.ra_products AS action
		CROSS JOIN boundary
		WHERE action.effective_at >= boundary.period_start_at
			AND action.effective_at <= in_effective_at
			AND (
				in_customer_ids IS NULL
				OR cardinality(in_customer_ids) = 0
				OR action.customer_id = ANY(in_customer_ids)
			)
			AND (
				in_customer_sale_place_ids IS NULL
				OR cardinality(in_customer_sale_place_ids) = 0
				OR action.customer_sale_place_id = ANY(in_customer_sale_place_ids)
			)
			AND (
				in_product_ids IS NULL
				OR cardinality(in_product_ids) = 0
				OR action.product_id = ANY(in_product_ids)
			)
			AND (
				in_measure_unit_ids IS NULL
				OR cardinality(in_measure_unit_ids) = 0
				OR action.measure_unit_id = ANY(in_measure_unit_ids)
			)
	)
	SELECT
		movements.customer_id,
		movements.customer_sale_place_id,
		movements.product_id,
		movements.measure_unit_id,
		SUM(movements.quant_required)::numeric(19, 4) AS quant_required,
		SUM(movements.quant)::numeric(19, 4) AS quant
	FROM movements
	GROUP BY
		movements.customer_id,
		movements.customer_sale_place_id,
		movements.product_id,
		movements.measure_unit_id
	HAVING SUM(movements.quant_required) <> 0 OR SUM(movements.quant) <> 0
	ORDER BY
		movements.customer_id,
		movements.customer_sale_place_id,
		movements.product_id,
		movements.measure_unit_id;
$function$;

COMMENT ON FUNCTION public.rg_products_balance(timestamptz, integer[], integer[], integer[], integer[]) IS 'Returns products register totals at an exact instant using completed monthly turnovers plus raw actions from the requested month.';

