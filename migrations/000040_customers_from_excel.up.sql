-- Insert one customer per INN. Existing customers with the same INN are reused.
INSERT INTO customers (
	name,
	inn,
	is_active
)
SELECT
	s.customer_name,
	s.inn,
	true
FROM (
	SELECT DISTINCT
		customer_name,
		inn
	FROM tmp_import_customer_sale_places_20260911
) AS s
WHERE NOT EXISTS (
	SELECT 1
	FROM customers AS c
	WHERE c.inn = s.inn
);

-- Insert sale places and attach them to the customer identified by INN.
-- If duplicate customer rows already exist for an INN, the smallest id is used.
-- The NOT EXISTS predicate matches the actual unique key semantics.
INSERT INTO customer_sale_places (
	customer_id,
	name,
	address,
	is_active
)
SELECT
	c.id,
	s.place_name,
	s.address,
	true
FROM tmp_import_customer_sale_places_20260911 AS s
JOIN LATERAL (
	SELECT c0.id
	FROM customers AS c0
	WHERE c0.inn = s.inn
	ORDER BY c0.id
	LIMIT 1
) AS c ON true
WHERE NOT EXISTS (
	SELECT 1
	FROM customer_sale_places AS csp
	WHERE csp.customer_id = c.id
		AND lower(csp.name) = lower(s.place_name)
);

