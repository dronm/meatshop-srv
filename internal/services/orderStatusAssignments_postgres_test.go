func orderStatusAssignmentsPostgres(t *testing.T) (*pgxpool.Pool, ds.Provider) {
	t.Helper()
	pool, provider := customerMessagePostgres(t)
	ctx := context.Background()
	// Keep the fixture independent of unrelated business migrations. The actual
	// status migration below installs the tracking/recalculation/audit behavior.
	if _, err := pool.Exec(ctx, `
		CREATE TABLE public.order_statuses (id integer PRIMARY KEY, code text, name text);
		INSERT INTO public.order_statuses VALUES
			(1, 'new', 'Новый'), (2, 'processing', 'В обработке'),
			(3, 'accepted', 'Готовим'), (4, 'approved', 'На доставке');
		CREATE FUNCTION public.order_statuses_ref(public.order_statuses) RETURNS json
		LANGUAGE sql AS $$ SELECT CASE WHEN $1.id IS NULL THEN NULL
			ELSE json_build_object('keys', json_build_object('id', $1.id), 'descr', $1.name) END $$;
		CREATE TABLE public.orders (
			id integer PRIMARY KEY, version bigint NOT NULL DEFAULT 1,
			status_id integer REFERENCES public.order_statuses(id), customer_user_id integer,
			ref_1c jsonb, cash_payed boolean NOT NULL DEFAULT false, comment_admin text
		);
		CREATE TABLE public.order_items (
			order_id integer, price numeric, amount numeric, vat_percent numeric,
			vat_amount numeric, use_marking boolean
		);
		INSERT INTO public.order_items(order_id, price, amount, vat_percent, vat_amount, use_marking)
		VALUES (101, 100, 200, 20, 33.33, true);
		CREATE SCHEMA integration_1c;
		CREATE TABLE integration_1c.jobs (command text, params jsonb);
		CREATE TABLE public.audit_column_aliases (
			table_name text, column_name text, column_alias text, is_active boolean,
			PRIMARY KEY (table_name, column_name)
		);
		CREATE TABLE public.status_test_audit (operation text, record_id bigint);
		CREATE FUNCTION public.audit_log_process() RETURNS trigger LANGUAGE plpgsql AS $$
		BEGIN
			INSERT INTO public.status_test_audit VALUES (TG_OP, COALESCE(NEW.id, OLD.id));
			RETURN NULL;
		END $$;
		CREATE TABLE public.order_status_assignments (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			order_id integer NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
			status_id integer REFERENCES public.order_statuses(id), recorder jsonb,
			is_active boolean NOT NULL DEFAULT true,
			recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
		);
		INSERT INTO public.orders(id, status_id) VALUES (101, 2), (102, NULL);
	`); err != nil {
		t.Fatal(err)
	}
	paths, err := filepath.Glob("../../migrations/*.up.sql")
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range paths {
		sql, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if strings.Contains(string(sql), "CREATE FUNCTION public.orders_track_status_assignment()") {
			if _, err := pool.Exec(ctx, string(sql)); err != nil {
				t.Fatalf("apply %s: %v", path, err)
			}
			return pool, provider
		}
	}
	t.Fatal("order status tracking migration not found")
	return nil, nil
}

func assertOrderStatusAssignmentState(t *testing.T, pool *pgxpool.Pool, orderID int, wantStatus *int, wantRecords, wantInactive int) {
	t.Helper()
	var status *int
	var records, inactive, current int
	if err := pool.QueryRow(context.Background(), `
		SELECT o.status_id, count(a.id)::integer,
			count(a.id) FILTER (WHERE NOT a.is_active)::integer,
			count(a.id) FILTER (WHERE a.is_current)::integer
		FROM public.orders AS o LEFT JOIN public.order_status_assignments_list AS a ON a.order_id = o.id
		WHERE o.id = $1 GROUP BY o.id
	`, orderID).Scan(&status, &records, &inactive, &current); err != nil {
		t.Fatal(err)
	}
	if !optionalIntEqual(status, wantStatus) || records != wantRecords || inactive != wantInactive || current != 1 {
		t.Fatalf("order %d: status=%v records=%d inactive=%d current=%d; want status=%v records=%d inactive=%d current=1",
			orderID, status, records, inactive, current, wantStatus, wantRecords, wantInactive)
	}
}

func TestOrderStatusAssignmentsPostgresOwnershipAndManualOverrides(t *testing.T) {
	pool, provider := orderStatusAssignmentsPostgres(t)
	ctx := context.Background()
	processing, production, delivery := 2, 3, 4
	assertOrderStatusAssignmentState(t, pool, 101, &processing, 1, 0)
	assertOrderStatusAssignmentState(t, pool, 102, nil, 1, 0)
	apply := func(fn func(ds.Querier) error) {
		t.Helper()
		if err := withPrimaryTransaction(ctx, provider, func(tx ds.Tx) error { return fn(tx) }); err != nil {
			t.Fatal(err)
		}
	}
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 101, 701) })
	assertOrderStatusAssignmentState(t, pool, 101, &production, 2, 0)
	var marked bool
	var price string
	if err := pool.QueryRow(ctx, `SELECT use_marking, price::text FROM public.order_items WHERE order_id = 101`).Scan(&marked, &price); err != nil || !marked || price != "100" {
		t.Fatalf("production transfer cleared item marking/prices: marked=%t price=%q err=%v", marked, price, err)
	}
	// Retrying the same owner does not create another record.
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 101, 701) })
	assertOrderStatusAssignmentState(t, pool, 101, &production, 2, 0)
	// An ordinary full-order save keeps ownership when the status is unchanged.
	if _, err := pool.Exec(ctx, `UPDATE public.orders SET status_id = status_id, comment_admin = 'Комментарий' WHERE id = 101`); err != nil {
		t.Fatal(err)
	}
	assertOrderStatusAssignmentState(t, pool, 101, &production, 2, 0)
	// Explicit same-value status selection is a manual assignment.
	apply(func(tx ds.Querier) error {
		_, err := changeOrderStatuses(ctx, tx, []int{101}, production)
		return err
	})
	assertOrderStatusAssignmentState(t, pool, 101, &production, 3, 0)
	apply(func(tx ds.Querier) error { return removeProductionOrderStatus(ctx, tx, 101, 701) })
	assertOrderStatusAssignmentState(t, pool, 101, &production, 3, 1)
	// Re-adding creates a fresh chronological assignment; withdrawing it still
	// preserves the earlier explicit manual choice of the very same status.
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 101, 701) })
	assertOrderStatusAssignmentState(t, pool, 101, &production, 4, 1)
	apply(func(tx ds.Querier) error { return removeProductionOrderStatus(ctx, tx, 101, 701) })
	assertOrderStatusAssignmentState(t, pool, 101, &production, 4, 2)
	// Direct/manual SQL status changes are also tracked, not only Go endpoints.
	if _, err := pool.Exec(ctx, `UPDATE public.orders SET status_id = $1 WHERE id = 101`, delivery); err != nil {
		t.Fatal(err)
	}
	assertOrderStatusAssignmentState(t, pool, 101, &delivery, 5, 2)
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 101, 702) })
	if _, err := pool.Exec(ctx, `UPDATE public.orders SET status_id = $1 WHERE id = 101`, processing); err != nil {
		t.Fatal(err)
	}
	apply(func(tx ds.Querier) error { return removeProductionOrderStatus(ctx, tx, 101, 702) })
	assertOrderStatusAssignmentState(t, pool, 101, &processing, 7, 3)
	// A null baseline is restored as null, rather than inventing another status.
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 102, 703) })
	apply(func(tx ds.Querier) error { return removeProductionOrderStatus(ctx, tx, 102, 703) })
	assertOrderStatusAssignmentState(t, pool, 102, nil, 2, 1)
	var manualCacheWrites int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.order_status_assignments
		WHERE order_id = 102 AND recorder IS NULL`).Scan(&manualCacheWrites); err != nil {
		t.Fatal(err)
	}
	if manualCacheWrites != 1 {
		t.Fatal("recalculation incorrectly recorded its cache update as a manual assignment")
	}
	var withdrawalsAudited int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.status_test_audit WHERE operation = 'UPDATE'`).Scan(&withdrawalsAudited); err != nil || withdrawalsAudited != 4 {
		t.Fatalf("withdrawals audited = %d, err=%v", withdrawalsAudited, err)
	}
}

func TestOrderStatusAssignmentsPostgresOlderWithdrawalAndRollback(t *testing.T) {
	pool, provider := orderStatusAssignmentsPostgres(t)
	ctx := context.Background()
	production, delivery := 3, 4
	apply := func(fn func(ds.Querier) error) {
		t.Helper()
		if err := withPrimaryTransaction(ctx, provider, func(tx ds.Tx) error { return fn(tx) }); err != nil {
			t.Fatal(err)
		}
	}
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 101, 801) })
	if _, err := pool.Exec(ctx, `UPDATE public.orders SET status_id = $1 WHERE id = 101`, delivery); err != nil {
		t.Fatal(err)
	}
	apply(func(tx ds.Querier) error { return addProductionOrderStatus(ctx, tx, 101, 802) })
	apply(func(tx ds.Querier) error { return removeProductionOrderStatus(ctx, tx, 101, 801) })
	assertOrderStatusAssignmentState(t, pool, 101, &production, 4, 1)
	apply(func(tx ds.Querier) error { return removeProductionOrderStatus(ctx, tx, 101, 802) })
	assertOrderStatusAssignmentState(t, pool, 101, &delivery, 4, 2)
	rollback := errors.New("test rollback")
	err := withPrimaryTransaction(ctx, provider, func(tx ds.Tx) error {
		if err := addProductionOrderStatus(ctx, tx, 101, 803); err != nil {
			return err
		}
		return rollback
	})
	if !errors.Is(err, rollback) {
		t.Fatalf("rollback error = %v", err)
	}
	assertOrderStatusAssignmentState(t, pool, 101, &delivery, 4, 2)
	if _, err := pool.Exec(ctx, `INSERT INTO public.orders(id, status_id) VALUES (103, NULL)`); err != nil {
		t.Fatal(err)
	}
	assertOrderStatusAssignmentState(t, pool, 103, nil, 1, 0)
}

func TestOrderStatusAssignmentsPostgresTrackingResumesInsideSameTransaction(t *testing.T) {
	pool, provider := orderStatusAssignmentsPostgres(t)
	ctx := context.Background()
	delivery := 4
	if err := withPrimaryTransaction(ctx, provider, func(tx ds.Tx) error {
		if err := addProductionOrderStatus(ctx, tx, 101, 901); err != nil {
			return err
		}
		if _, err := tx.Exec(ctx, `UPDATE public.orders SET status_id = $1 WHERE id = 101`, delivery); err != nil {
			return err
		}
		return removeProductionOrderStatus(ctx, tx, 101, 901)
	}); err != nil {
		t.Fatal(err)
	}
	assertOrderStatusAssignmentState(t, pool, 101, &delivery, 3, 1)
}
