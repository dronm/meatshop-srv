func productionTransferPostgres(t *testing.T) (*pgxpool.Pool, ds.Provider) {
	t.Helper()
	pool, provider := orderStatusAssignmentsPostgres(t)
	ctx := context.Background()
	_, err := pool.Exec(ctx, `
		ALTER TABLE public.orders ADD COLUMN for_date date NOT NULL DEFAULT '2026-11-14',
			ADD COLUMN number_1c text, ADD COLUMN customer_id integer NOT NULL DEFAULT 1,
			ADD COLUMN customer_sale_place_id integer, ADD COLUMN customer_name text,
			ADD COLUMN customer_phone text, ADD COLUMN comment_customer text;
		CREATE TABLE public.customer_sale_places(id integer PRIMARY KEY,name text);
		CREATE FUNCTION public.customer_sale_places_ref(public.customer_sale_places) RETURNS json LANGUAGE sql AS $$
			SELECT json_build_object('keys',json_build_object('id',$1.id),'descr',$1.name) $$;
		CREATE TABLE public.products(id integer PRIMARY KEY,name text);
		CREATE TABLE public.measure_units(id integer PRIMARY KEY,name text);
		ALTER TABLE public.order_items ADD COLUMN id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			ADD COLUMN product_id integer, ADD COLUMN measure_unit_id integer,
			ADD COLUMN quant numeric(19,4), ADD COLUMN line_num integer NOT NULL DEFAULT 1;
		CREATE TABLE public.webapp_constants(code text PRIMARY KEY,value_type text,value jsonb);
		INSERT INTO public.webapp_constants VALUES('production_max_chat_id','string','"-12345"');
		CREATE TABLE public.max_out_messages(
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,max_user_id bigint,max_chat_id bigint,
			message jsonb NOT NULL,metadata jsonb NOT NULL DEFAULT '{}',status text NOT NULL DEFAULT 'pending',
			attempt_count integer NOT NULL DEFAULT 0,next_attempt_at timestamptz,locked_at timestamptz,
			sent_at timestamptz,error_str text,created_at timestamptz NOT NULL DEFAULT now(),
			delivery_key text,sequence_key text,sequence_num integer
		);
		CREATE UNIQUE INDEX production_test_delivery_key ON public.max_out_messages(delivery_key) WHERE delivery_key IS NOT NULL;
		INSERT INTO public.customer_sale_places VALUES(1,'Первая точка');
		UPDATE public.orders SET customer_sale_place_id=1 WHERE id=101;
		INSERT INTO public.orders(id,status_id,customer_id) VALUES(103,2,2);
		INSERT INTO public.products VALUES(1,'Филе'),(2,'Яйцо');
		INSERT INTO public.measure_units VALUES(1,'кг'),(2,'кор');
		INSERT INTO public.order_items(order_id,product_id,measure_unit_id,quant,use_marking)
		VALUES(101,1,1,0.1,true),(103,1,1,0.2,false),(103,2,2,2,false);
	`)
	if err != nil {
		t.Fatal(err)
	}
	for _, pattern := range []string{"*_create_production_transfers.up.sql", "*_create_production_transfer_orders.up.sql", "*_production_transfer_support.up.sql"} {
		paths, err := filepath.Glob(filepath.Join("..", "..", "migrations", pattern))
		if err != nil || len(paths) != 1 {
			t.Fatalf("find migration %s: %v %v", pattern, paths, err)
		}
		data, err := os.ReadFile(paths[0])
		if err != nil {
			t.Fatal(err)
		}
		if _, err := pool.Exec(ctx, string(data)); err != nil {
			t.Fatalf("apply %s: %v", paths[0], err)
		}
	}
	return pool, provider
}

func TestProductionTransferPostgresEditableOwnershipLiveDataAndOutbox(t *testing.T) {
	pool, provider := productionTransferPostgres(t)
	ctx := context.Background()
	service := &ProductionTransferService{DB: provider, Session: customerMessageTestSession{user: models.UserLogin{ID: 101, RoleID: models.RoleIDAdmin}}}
	preview, err := service.Prepare(ctx, models.ProductionTransferPrepareRequest{OrderIDs: []int{101, 103, 101, 102}})
	if err != nil {
		t.Fatal(err)
	}
	if len(preview.Orders) != 2 || len(preview.Skipped) != 1 {
		t.Fatalf("preview=%#v", preview)
	}
	input := &models.ProductionTransferInput{DocumentDate: "2026-11-13", ForDate: "2026-11-14", OrderIDs: []int{101, 103}, RequestID: "production-integration-request"}
	doc, err := service.Create(ctx, input)
	if err != nil {
		t.Fatal(err)
	}
	if len(doc.Orders) != 2 || doc.Version != 1 || doc.NotificationStatus != "pending" {
		t.Fatalf("created document=%#v", doc)
	}
	assertProductionEffectiveStatus(t, pool, 101, 3)
	assertProductionEffectiveStatus(t, pool, 103, 3)
	duplicate, err := service.Create(ctx, input)
	if err != nil || duplicate.ID != doc.ID {
		t.Fatalf("idempotent create=%#v err=%v", duplicate, err)
	}
	input.Version = doc.Version
	unchanged, err := service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil || unchanged.Version != 1 {
		t.Fatalf("unchanged save=%#v err=%v", unchanged, err)
	}
	var messages int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.max_out_messages`).Scan(&messages); err != nil || messages != 2 {
		t.Fatalf("duplicate queue entries=%d err=%v", messages, err)
	}
	// Later manual status must survive withdrawing this document's assignment.
	if _, err := pool.Exec(ctx, `UPDATE public.orders SET status_id=4 WHERE id=101`); err != nil {
		t.Fatal(err)
	}
	input.OrderIDs = []int{103}
	doc, err = service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil {
		t.Fatal(err)
	}
	assertProductionEffectiveStatus(t, pool, 101, 4)
	assertProductionEffectiveStatus(t, pool, 103, 3)
	input.Version = doc.Version
	input.OrderIDs = []int{}
	doc, err = service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil {
		t.Fatal(err)
	}
	if len(doc.Orders) != 0 {
		t.Fatal("last order could not be removed")
	}
	assertProductionEffectiveStatus(t, pool, 103, 2)
	// Re-add after a manual move back to processing, preserving old withdrawn history.
	if _, err := pool.Exec(ctx, `UPDATE public.orders SET status_id=2 WHERE id=101`); err != nil {
		t.Fatal(err)
	}
	input.Version = doc.Version
	input.OrderIDs = []int{101}
	doc, err = service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil {
		t.Fatal(err)
	}
	assertProductionEffectiveStatus(t, pool, 101, 3)
	var recordsBefore int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.order_status_assignments WHERE order_id=101`).Scan(&recordsBefore); err != nil {
		t.Fatal(err)
	}
	// A current source quantity changes the live projection and re-sending Save
	// queues revised text without reposting this document's status assignment.
	if _, err := pool.Exec(ctx, `UPDATE public.order_items SET quant=0.7 WHERE order_id=101`); err != nil {
		t.Fatal(err)
	}
	input.Version = doc.Version
	updated, err := service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil {
		t.Fatal(err)
	}
	if updated.Version != doc.Version+1 || !strings.Contains(updated.Orders[0].Products, "0,7") {
		t.Fatalf("live change not reflected: %#v", updated)
	}
	var recordsAfter int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.order_status_assignments WHERE order_id=101`).Scan(&recordsAfter); err != nil || recordsAfter != recordsBefore {
		t.Fatalf("ordinary save reposted status: %d -> %d err=%v", recordsBefore, recordsAfter, err)
	}
	printed, err := GetProductionTransferPrint(ctx, provider, doc.ID)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(printed), "0,7 кг") || !strings.Contains(string(printed), `class="mark">Да`) {
		t.Fatal("print did not use live quantity/item marking")
	}
	// Long revised messages retain the same split boundaries on an unchanged
	// subsequent save; revision headings count toward MAX's character limit.
	if _, err := pool.Exec(ctx, `UPDATE public.products SET name=$1 WHERE id=1`, strings.Repeat("Длинное название ", 700)); err != nil {
		t.Fatal(err)
	}
	input.Version = updated.Version
	longDocument, err := service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil {
		t.Fatal(err)
	}
	input.Version = longDocument.Version
	longUnchanged, err := service.Update(ctx, models.ProductionTransferUpdateRequest{ID: doc.ID, Document: input})
	if err != nil || longUnchanged.Version != longDocument.Version {
		t.Fatalf("unchanged long document resent: %#v err=%v", longUnchanged, err)
	}
	// Missing destination causes the complete document/status transaction to roll back.
	if _, err := pool.Exec(ctx, `UPDATE public.webapp_constants SET value='null' WHERE code='production_max_chat_id'`); err != nil {
		t.Fatal(err)
	}
	if _, err := service.Create(ctx, &models.ProductionTransferInput{DocumentDate: "2026-11-13", ForDate: "2026-11-14", OrderIDs: []int{103}, RequestID: "unset-chat"}); err == nil {
		t.Fatal("document committed without configured destination")
	}
	assertProductionEffectiveStatus(t, pool, 103, 2)
	var docs int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.production_transfers`).Scan(&docs); err != nil || docs != 1 {
		t.Fatalf("rollback left document: %d err=%v", docs, err)
	}
	if _, err := service.Delete(ctx, doc.ID); err != nil {
		t.Fatal(err)
	}
	assertProductionEffectiveStatus(t, pool, 101, 2)
	var pending int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.max_out_messages WHERE status IN ('pending','sending')`).Scan(&pending); err != nil || pending != 0 {
		t.Fatalf("deleted doc retained pending messages: %d err=%v", pending, err)
	}
}

func assertProductionEffectiveStatus(t *testing.T, pool *pgxpool.Pool, orderID, want int) {
	t.Helper()
	var got int
	if err := pool.QueryRow(context.Background(), `SELECT status_id FROM public.orders WHERE id=$1`, orderID).Scan(&got); err != nil || got != want {
		t.Fatalf("order%d status=%d want%d err=%v", orderID, got, want, err)
	}
}
