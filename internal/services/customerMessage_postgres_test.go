// These tests create and drop their own database. Point this at a disposable
// PostgreSQL server whose test user has CREATEDB; no existing schema is modified.
func customerMessagePostgres(t *testing.T) (*pgxpool.Pool, ds.Provider) {
	t.Helper()
	dsn := os.Getenv("MEATSHOP_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set MEATSHOP_TEST_DATABASE_URL to run isolated PostgreSQL tests")
	}
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	name := fmt.Sprintf("meatshop_messages_test_%d", time.Now().UnixNano())
	if _, err := admin.Exec(ctx, "CREATE DATABASE "+pgx.Identifier{name}.Sanitize()); err != nil {
		admin.Close(ctx)
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_, err := admin.Exec(ctx, "DROP DATABASE "+pgx.Identifier{name}.Sanitize()+" WITH (FORCE)")
		if err != nil {
			t.Error(err)
		}
		admin.Close(ctx)
	})
	testURL, err := url.Parse(dsn)
	if err != nil || testURL.Scheme != "postgres" && testURL.Scheme != "postgresql" {
		t.Fatalf("MEATSHOP_TEST_DATABASE_URL must be a PostgreSQL URL: %v", err)
	}
	testURL.Path = "/" + name
	cfg, err := pgxpool.ParseConfig(testURL.String())
	if err != nil {
		t.Fatal(err)
	}
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	provider, err := pgds.New(&pgds.Config{PrimaryConnStr: testURL.String()})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = provider.Close() })
	_, err = pool.Exec(ctx, `
		CREATE TYPE public.role_types AS ENUM ('admin', 'customer');
		CREATE TABLE public.customers (id integer PRIMARY KEY, name text NOT NULL);
		CREATE TABLE public.users (id integer PRIMARY KEY);
		CREATE TABLE public.max_users (
			id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			max_user_id bigint UNIQUE NOT NULL, customer_id integer REFERENCES public.customers(id),
			app_username text NOT NULL, username text, raw_user jsonb NOT NULL DEFAULT '{}', is_active boolean DEFAULT true
		);
		CREATE TABLE public.max_in_messages (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			update_type text NOT NULL, max_user_id bigint, max_chat_id bigint,
			message jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
		);
		CREATE TABLE public.permissions (code text PRIMARY KEY, description text);
		CREATE TABLE public.role_permissions (
			role_id public.role_types, permission_code text REFERENCES public.permissions(code),
			PRIMARY KEY (role_id, permission_code)
		);
		CREATE TABLE public.application_routes (
			id serial PRIMARY KEY, name text UNIQUE, path text, descr text, section text, icon text,
			menu_available boolean, is_active boolean
		);
		CREATE TABLE public.main_menus (
			id serial PRIMARY KEY, role_id public.role_types, user_id integer, parent_id integer,
			caption text, route_id integer REFERENCES public.application_routes(id), icon text,
			sort_order integer, is_active boolean
		);
		INSERT INTO public.customers VALUES (1, 'First customer'), (2, 'Second customer');
		INSERT INTO public.users VALUES (101), (102), (103);
		INSERT INTO public.max_users (max_user_id, customer_id, app_username)
		VALUES (8001, 1, 'Customer person');
		INSERT INTO public.main_menus (role_id, caption) VALUES ('admin', 'Покупатели');
	`)
	if err != nil {
		t.Fatal(err)
	}
	// The same old message was delivered twice before deduplication existed.
	for range 2 {
		if _, err := pool.Exec(ctx, `INSERT INTO public.max_in_messages
			(update_type, max_user_id, message, created_at) VALUES ('message_created', 8001, $1, '2026-11-01T10:00:00Z')`,
			string(customerMessageRaw("old-message", 8001, "Existing message"))); err != nil {
			t.Fatal(err)
		}
	}
	applyCustomerMessageMigration(t, pool, "up")
	return pool, provider
}

func applyCustomerMessageMigration(t *testing.T, pool *pgxpool.Pool, direction string) {
	t.Helper()
	path := filepath.Join("..", "..", "migrations", "000074_customer_messages."+direction+".sql")
	sql, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pool.Exec(context.Background(), string(sql)); err != nil {
		t.Fatalf("migration %s: %v", direction, err)
	}
}

func customerMessageRaw(mid string, sender int64, text string) json.RawMessage {
	return json.RawMessage(fmt.Sprintf(`{"update_type":"message_created","message":{
		"sender":{"user_id":%d,"first_name":"Sender","is_bot":false},
		"recipient":{"chat_id":9001,"chat_type":"dialog"},
		"timestamp":1794650400123,"body":{"mid":%q,"text":%q}}}`, sender, mid, text))
}

func saveCustomerMessage(t *testing.T, pool *pgxpool.Pool, raw json.RawMessage) {
	t.Helper()
	var update maxbot.Update
	if err := json.Unmarshal(raw, &update); err != nil {
		t.Fatal(err)
	}
	if err := maxbot.NewStore(pool).SaveUpdate(context.Background(), raw, update, nil); err != nil {
		t.Fatal(err)
	}
}

func customerMessageAdmin(provider ds.Provider, id int) *CustomerMessageService {
	return &CustomerMessageService{DB: provider, Session: customerMessageTestSession{
		user: models.UserLogin{ID: id, RoleID: models.RoleIDAdmin},
	}}
}

func TestCustomerMessagePostgresIngestion(t *testing.T) {
	pool, provider := customerMessagePostgres(t)
	ctx := context.Background()
	listener, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Release()
	if _, err := listener.Exec(ctx, `LISTEN "CustomerMessage.Create"`); err != nil {
		t.Fatal(err)
	}
	raw := customerMessageRaw("live-message", 8001, "  Hello\nCustomer text  ")
	saveCustomerMessage(t, pool, raw)
	deadline, cancel := context.WithTimeout(ctx, 2*time.Second)
	defer cancel()
	notification, err := listener.Conn().WaitForNotification(deadline)
	if err != nil || notification.Channel != "CustomerMessage.Create" {
		t.Fatalf("notification = %v, err = %v", notification, err)
	}
	saveCustomerMessage(t, pool, raw)
	quiet, stop := context.WithTimeout(ctx, 100*time.Millisecond)
	defer stop()
	if extra, err := listener.Conn().WaitForNotification(quiet); err == nil {
		t.Fatalf("duplicate notification: %v", extra)
	}
	var row models.CustomerMessage
	err = pool.QueryRow(ctx, `SELECT customer_id, sender_name, text, sent_at
		FROM public.customer_messages WHERE max_message_id = 'live-message'`).Scan(
		&row.CustomerID, &row.SenderName, &row.Text, &row.SentAt)
	if err != nil || row.CustomerID == nil || *row.CustomerID != 1 || row.SenderName != "Customer person" ||
		row.Text != "  Hello\nCustomer text  " || row.SentAt.UnixMilli() != 1794650400123 {
		t.Fatalf("message = %#v, err = %v", row, err)
	}
	for _, raw := range []json.RawMessage{
		json.RawMessage(`{"update_type":"message_removed","user":{"user_id":8001}}`),
		json.RawMessage(`{"update_type":"message_created","message":{"sender":{"user_id":8001,"is_bot":true},"body":{"mid":"bot","text":"Bot text"}}}`),
		json.RawMessage(`{"update_type":"message_created","message":{"sender":{"user_id":8001},"recipient":{"chat_type":"chat"},"body":{"mid":"group","text":"Group text"}}}`),
		json.RawMessage(`{"update_type":"message_created","message":{"sender":{"user_id":8001},"body":{"mid":"attachment","text":null}}}`),
		customerMessageRaw("blank", 8001, " \t\n "),
	} {
		saveCustomerMessage(t, pool, raw)
	}
	list, err := customerMessageAdmin(provider, 101).List(ctx, modelbind.CollectionParams{})
	if err != nil || len(list.Rows) != 2 || list.Rows[0].MaxMessageID != "live-message" {
		t.Fatalf("list = %#v, err = %v", list, err)
	}
}

func TestCustomerMessagePostgresReadState(t *testing.T) {
	pool, provider := customerMessagePostgres(t)
	ctx := context.Background()
	saveCustomerMessage(t, pool, customerMessageRaw("second-message", 8001, "New message"))
	first, second := customerMessageAdmin(provider, 101), customerMessageAdmin(provider, 102)
	list, err := first.List(ctx, modelbind.CollectionParams{})
	if err != nil {
		t.Fatal(err)
	}
	id := list.Rows[0].ID
	if _, err := first.Detail(ctx, id); err != nil {
		t.Fatal(err)
	}
	for _, svc := range []*CustomerMessageService{first, second} {
		count, err := svc.UnreadCount(ctx, nil)
		if err != nil || count.UnreadCount != 2 {
			t.Fatalf("count = %v, err = %v", count, err)
		}
	}
	request := models.CustomerMessageMarkReadRequest{MessageIDs: []int64{id, id}}
	if result, err := first.MarkRead(ctx, request); err != nil || result.RowsAffected != 1 {
		t.Fatalf("mark read = %v, err = %v", result, err)
	}
	if result, err := first.MarkRead(ctx, request); err != nil || result.RowsAffected != 0 {
		t.Fatalf("repeat read = %v, err = %v", result, err)
	}
	for index, svc := range []*CustomerMessageService{first, second} {
		count, err := svc.UnreadCount(ctx, nil)
		if err != nil || count.UnreadCount != int64(index+1) {
			t.Fatalf("admin %d count = %v, err = %v", index, count, err)
		}
	}
	oldID := list.Rows[1].ID
	if _, err := first.MarkRead(ctx, models.CustomerMessageMarkReadRequest{MessageIDs: []int64{oldID, 999999}}); err == nil {
		t.Fatal("missing message accepted")
	}
	params := modelbind.CollectionParams{Filter: []modelbind.CollectionFilter{{Fields: map[string]modelbind.CollectionFilterField{
		"customer_id": {Operator: modelbind.FilterOperParEq, Value: 1},
		"is_read":     {Operator: modelbind.FilterOperParEq, Value: false},
	}}}}
	unread, err := first.List(ctx, params)
	if err != nil || len(unread.Rows) != 1 || unread.Rows[0].ID != oldID || unread.Rows[0].ReadAt != nil {
		t.Fatalf("unread list = %#v, err = %v", unread, err)
	}
	saveCustomerMessage(t, pool, customerMessageRaw("arrived-during-read", 8001, "Do not mark this unseen message"))
	if _, err := first.MarkRead(ctx, models.CustomerMessageMarkReadRequest{MessageIDs: []int64{oldID}}); err != nil {
		t.Fatal(err)
	}
	count, err := first.UnreadCount(ctx, nil)
	if err != nil || count.UnreadCount != 1 {
		t.Fatalf("new message was hidden: count = %v, err = %v", count, err)
	}
	first.Session = customerMessageTestSession{user: models.UserLogin{ID: 103, RoleID: "customer"}}
	if _, err := first.List(ctx, modelbind.CollectionParams{}); err == nil {
		t.Fatal("customer could list messages")
	}
	if _, err := first.Detail(ctx, id); err == nil {
		t.Fatal("customer could read a message")
	}
	if _, err := first.MarkRead(ctx, request); err == nil {
		t.Fatal("customer could acknowledge a message")
	}
	if _, err := first.UnreadCount(ctx, nil); err == nil {
		t.Fatal("customer could count messages")
	}
}

func TestCustomerMessagePostgresBindingAndCommit(t *testing.T) {
	pool, _ := customerMessagePostgres(t)
	ctx := context.Background()
	saveCustomerMessage(t, pool, customerMessageRaw("unassigned-message", 8002, "Before registration"))
	if _, err := pool.Exec(ctx, `INSERT INTO public.max_users (max_user_id, customer_id, app_username)
		VALUES (8002, 1, 'New user'); UPDATE public.max_users SET customer_id = 2 WHERE max_user_id = 8002`); err != nil {
		t.Fatal(err)
	}
	var customerID int
	if err := pool.QueryRow(ctx, `SELECT customer_id FROM public.customer_messages WHERE max_message_id = 'unassigned-message'`).Scan(&customerID); err != nil || customerID != 1 {
		t.Fatalf("original customer changed: customer_id = %d, err = %v", customerID, err)
	}
	for i := range 10 {
		maxID := int64(8100 + i)
		mid := fmt.Sprintf("concurrent-%d", i)
		var group sync.WaitGroup
		group.Add(2)
		go func() {
			defer group.Done()
			var update maxbot.Update
			raw := customerMessageRaw(mid, maxID, "While registering")
			_ = json.Unmarshal(raw, &update)
			if err := maxbot.NewStore(pool).SaveUpdate(ctx, raw, update, nil); err != nil {
				t.Error(err)
			}
		}()
		go func() {
			defer group.Done()
			if _, err := pool.Exec(ctx, `INSERT INTO public.max_users (max_user_id, customer_id, app_username)
				VALUES ($1, 1, 'Concurrent user')`, maxID); err != nil {
				t.Error(err)
			}
		}()
		group.Wait()
		if err := pool.QueryRow(ctx, `SELECT customer_id FROM public.customer_messages WHERE max_message_id = $1`, mid).Scan(&customerID); err != nil || customerID != 1 {
			t.Fatalf("concurrent binding missed: customer_id = %d, err = %v", customerID, err)
		}
	}
	listener, err := pool.Acquire(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Release()
	if _, err := listener.Exec(ctx, `LISTEN "CustomerMessage.Create"`); err != nil {
		t.Fatal(err)
	}
	tx, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback(ctx)
	if _, err := tx.Exec(ctx, `INSERT INTO public.max_in_messages (update_type, max_user_id, message)
		VALUES ('message_created', 8001, $1)`, string(customerMessageRaw("rolled-back", 8001, "Do not notify"))); err != nil {
		t.Fatal(err)
	}
	quiet, cancel := context.WithTimeout(ctx, 100*time.Millisecond)
	defer cancel()
	if notification, err := listener.Conn().WaitForNotification(quiet); err == nil {
		t.Fatalf("notification before commit: %v", notification)
	}
	if err := tx.Rollback(ctx); err != nil {
		t.Fatal(err)
	}
	var count int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.customer_messages WHERE max_message_id = 'rolled-back'`).Scan(&count); err != nil || count != 0 {
		t.Fatalf("rolled-back message persisted: %d, err = %v", count, err)
	}
}

func TestCustomerMessagePostgresMigrationRoundTrip(t *testing.T) {
	pool, _ := customerMessagePostgres(t)
	ctx := context.Background()
	applyCustomerMessageMigration(t, pool, "down")
	var exists bool
	if err := pool.QueryRow(ctx, `SELECT to_regclass('public.customer_messages') IS NOT NULL`).Scan(&exists); err != nil || exists {
		t.Fatalf("down migration left messages table: exists = %v, err = %v", exists, err)
	}
	applyCustomerMessageMigration(t, pool, "up")
	var count int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.customer_messages`).Scan(&count); err != nil || count != 1 {
		t.Fatalf("round-trip backfill = %d, err = %v", count, err)
	}
}
