package services

import (
	"context"
	"os"
	"sync"
	"testing"

	"github.com/dronm/meatshop/internal/models"
)

func TestMaxChatPostgresConversation(t *testing.T) {
	pool, provider := customerMessagePostgres(t)
	ctx := context.Background()
	exec := func(sql string, args ...any) {
		t.Helper()
		if _, err := pool.Exec(ctx, sql, args...); err != nil {
			t.Fatal(err)
		}
	}
	exec(`ALTER TABLE public.users ADD COLUMN name text NOT NULL DEFAULT 'Operator';
		CREATE TABLE public.orders (id integer PRIMARY KEY, customer_id integer, customer_user_id integer);
		CREATE TABLE public.max_out_messages (
			id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			max_user_id bigint REFERENCES public.max_users(max_user_id) ON DELETE CASCADE,
			message jsonb NOT NULL, metadata jsonb NOT NULL DEFAULT '{}', created_at timestamptz NOT NULL DEFAULT now(),
			status text NOT NULL DEFAULT 'pending', attempt_count integer NOT NULL DEFAULT 0, sent_at timestamptz,
			remote_message_id text, error_str text, delivery_key text
		);
		INSERT INTO public.max_users (max_user_id, customer_id, app_username, username)
		VALUES (9007199254740993, 1, 'Another contact', 'AnotherHandle');
		INSERT INTO public.orders VALUES (10, 1, 1), (11, 1, NULL);
		INSERT INTO public.max_out_messages (max_user_id, message, metadata) VALUES
			(8001, '{"text":"Historic order change"}', '{"entity_type":"order","entity_id":10,"event":"order.changed"}'),
			(8001, '{"text":"Internal change"}', '{"entity_type":"order","entity_id":10,"event":"order.changed","audience":"staff"}');`)
	migration, err := os.ReadFile("../../migrations/000090_max_chat.up.sql")
	if err != nil {
		t.Fatal(err)
	}
	exec(string(migration))
	svc := customerMessageAdmin(provider, 101)
	svc.Session = customerMessageTestSession{user: models.UserLogin{ID: 101, Name: "Operator", RoleID: models.RoleIDAdmin}}
	participants, err := svc.ChatParticipants(ctx, models.MaxChatParticipantsRequest{Query: "anotherhandle"})
	if err != nil || len(participants.Rows) != 1 || participants.Rows[0].MaxUserID != "9007199254740993" {
		t.Fatalf("search for linked user without orders: %#v, %v", participants, err)
	}
	linked, err := svc.ChatParticipants(ctx, models.MaxChatParticipantsRequest{CustomerID: 1, MessageID: "1"})
	if err != nil || len(linked.Rows) != 1 || linked.Rows[0].MaxUserID != "8001" {
		t.Fatalf("sender of the inbox message: %#v, %v", linked, err)
	}
	for orderID, want := range map[int]int{10: 1, 11: 0} {
		page, err := svc.ChatParticipants(ctx, models.MaxChatParticipantsRequest{OrderID: orderID})
		if err != nil || len(page.Rows) != want || want > 0 && page.Rows[0].UserID != 1 {
			t.Fatalf("order %d recipient: %#v, %v", orderID, page, err)
		}
	}
	input := models.MaxChatSendRequest{CustomerID: 1, UserID: 1, RequestID: "641a891e-6dcc-4169-a6d2-b043c0fe7990", Text: "Can you confirm the quantity?"}
	// Two concurrent submissions must return the same queued message.
	var replies [2]*models.MaxChatMessage
	var sendErrors [2]error
	var senders sync.WaitGroup
	for index := range replies {
		senders.Add(1)
		go func(i int) {
			defer senders.Done()
			replies[i], sendErrors[i] = svc.ChatSend(ctx, input)
		}(index)
	}
	senders.Wait()
	if sendErrors[0] != nil || sendErrors[1] != nil || replies[0].ID != replies[1].ID || replies[0].Kind != "manual" {
		t.Fatalf("concurrent replies: %#v %#v, errors %v", replies[0], replies[1], sendErrors)
	}
	var queued int
	if err := pool.QueryRow(ctx, `SELECT count(*) FROM public.max_out_messages WHERE message->>'text'=$1`, input.Text).Scan(&queued); err != nil || queued != 1 {
		t.Fatalf("queued copies = %d, err = %v", queued, err)
	}
	exec(`UPDATE public.max_out_messages SET status='sent', sent_at=now(), remote_message_id='mid.123' WHERE message->>'text'=$1`, input.Text)
	exec(`INSERT INTO public.max_out_messages (max_user_id, message, metadata) VALUES
		(8001, '{"text":"New order change"}', '{"entity_type":"order","entity_id":10,"event":"order.changed","audience":"customer"}');`)
	// Deliberately collide the timestamp across incoming, manual and automatic rows.
	exec(`UPDATE public.max_chat_outgoing SET created_at='2026-11-10T12:00:00.123456Z';
		UPDATE public.customer_messages SET sent_at='2026-11-10T12:00:00.123456Z'`)
	history := models.MaxChatHistoryRequest{CustomerID: 1, UserID: 1, Limit: 2}
	page, err := svc.ChatHistory(ctx, history)
	if err != nil || !page.HasMore || len(page.Rows) != 2 || page.Rows[0].Text != input.Text || page.Rows[0].Status == nil || *page.Rows[0].Status != "sent" || page.Rows[1].Text != "New order change" {
		t.Fatalf("latest page: %#v, %v", page, err)
	}
	history.Before = page.Rows[0].Cursor
	previous, err := svc.ChatHistory(ctx, history)
	if err != nil || previous.HasMore || len(previous.Rows) != 2 || previous.Rows[0].Kind != "incoming" || previous.Rows[1].Kind != "automatic" || previous.Rows[1].Text != "Historic order change" {
		t.Fatalf("previous page: %#v, %v", previous, err)
	}
	history.Before = ""
	history.After = previous.Rows[1].Cursor
	later, err := svc.ChatHistory(ctx, history)
	if err != nil || later.HasMore || len(later.Rows) != 2 || later.Rows[0].ID != replies[0].ID {
		t.Fatalf("catch-up page: %#v, %v", later, err)
	}
	if count, err := svc.UnreadCount(ctx, nil); err != nil || count.UnreadCount != 1 {
		t.Fatalf("outgoing changed unread count: %#v, %v", count, err)
	}
	input.OrderID = 10
	input.RequestID = "58a54120-298f-4493-84e9-3db385b87de5"
	exec(`UPDATE public.orders SET customer_user_id=2 WHERE id=10`)
	if _, err := svc.ChatSend(ctx, input); err == nil {
		t.Fatal("sent from a stale order after its recipient changed")
	}
	input.OrderID = 0
	exec(`UPDATE public.max_users SET is_active=false WHERE id=1`)
	if _, err := svc.ChatSend(ctx, input); err == nil {
		t.Fatal("sent to an inactive MAX recipient")
	}
	exec(`UPDATE public.max_users SET is_active=true WHERE id=1`)
	exec(`UPDATE public.max_users SET customer_id=2 WHERE id=1`)
	input.RequestID = "fd15203f-1d98-4d37-935c-9a964c042889"
	if _, err := svc.ChatSend(ctx, input); err == nil {
		t.Fatal("sent to a MAX user who moved to a different customer")
	}
	newCustomer, err := svc.ChatHistory(ctx, models.MaxChatHistoryRequest{CustomerID: 2, UserID: 1})
	if err != nil || len(newCustomer.Rows) != 0 {
		t.Fatalf("history crossed customer boundary: %#v, %v", newCustomer, err)
	}
}
